#!/usr/bin/env node
/* build-step-nav.mjs — stamps every asset page with its position in The Method.
 *
 *   node scripts/build-step-nav.mjs
 *
 * /tools/ tells the story to someone who lands there. Most people don't — they
 * arrive on a decision tree from search, read it, and leave, with no idea it
 * was step 4 of something. This puts the arc on the page itself: which step
 * this is, what came before, what comes next.
 *
 * Idempotent — replaces the block between the markers on re-run.
 */

import { readFileSync, writeFileSync, globSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const STEPS = [
  "Name it", "Locate it", "Check it", "Decide it",
  "Design &amp; sequence it", "Prove it", "Go deeper",
];

/* First matching rule wins, so order matters. */
const RULES = [
  [/^situations\//, 1],
  [/^for\//, 1],
  [/^how-i-work\//, 1],
  [/^tools\/calculators\//, 6],          // before the generic tools/ rule
  [/^tools\/compound\//, 2],
  [/^tools\/[a-z-]+\.html$/, 2],
  [/^dataset\//, 3],
  [/^glossary\//, 3],
  [/^reading\//, 3],
  [/^anti-patterns\//, 3],
  [/^maturity\//, 3],
  [/^observability\//, 3],
  [/^security\//, 3],
  [/^decisions\//, 4],
  [/^reference-architectures\//, 5],
  [/^playbooks\//, 5],
  [/^oss\//, 5],
  [/^teardowns\//, 7],
  [/^writing\//, 7],
  [/^case-studies\//, 7],
  [/^state-of-2026\//, 7],
];

/* Hubs and one-offs that are not a step in the arc. */
const SKIP = new Set([
  "index.html", "tools/index.html", "press/index.html", "talks/index.html",
  "letters/index.html", "ai/index.html", "4-discipline-stack/index.html",
  "thanks/index.html",
]);

const START = "<!-- STEP-NAV:START — generated by scripts/build-step-nav.mjs -->";
const END = "<!-- STEP-NAV:END -->";

function block(step) {
  const i = step - 1;
  const prev = i > 0
    ? `<a href="/tools/#s${step - 1}">&larr; ${String(step - 1).padStart(2, "0")} ${STEPS[i - 1]}</a>`
    : `<span class="edge">start of the arc</span>`;
  const next = i < STEPS.length - 1
    ? `<a href="/tools/#s${step + 1}">${String(step + 1).padStart(2, "0")} ${STEPS[i + 1]} &rarr;</a>`
    : `<a href="/situations/">back to 01 Name it &rarr;</a>`;

  return `${START}
  <nav class="step-nav" aria-label="Position in The Method">
    <div class="wrap">
      <a class="lab" href="/tools/">The Method</a>
      <div class="row">
        ${prev}
        <b>${String(step).padStart(2, "0")} &middot; ${STEPS[i]}</b>
        ${next}
      </div>
    </div>
  </nav>
  ${END}`;
}

const files = globSync("**/*.html", { cwd: ROOT })
  .filter(f => !f.startsWith("node_modules") && !SKIP.has(f));

let stamped = 0, skipped = 0;
const counts = {};

for (const f of files) {
  const rule = RULES.find(([re]) => re.test(f));
  if (!rule) { skipped++; continue; }
  const step = rule[1];

  let html = readFileSync(join(ROOT, f), "utf8");
  const nav = block(step);

  if (html.includes(START)) {
    html = html.replace(new RegExp(`${START}[\\s\\S]*?${END}`), nav);
  } else {
    /* Sits immediately above the also-strip, or the footer if there isn't one. */
    const anchor = html.includes('<section class="also-strip"')
      ? html.indexOf('<section class="also-strip"')
      : html.indexOf("<footer");
    if (anchor === -1) { skipped++; continue; }
    /* Keep the surrounding indentation tidy. */
    const lineStart = html.lastIndexOf("\n", anchor) + 1;
    html = html.slice(0, lineStart) + nav + "\n\n" + html.slice(lineStart);
  }
  writeFileSync(join(ROOT, f), html, "utf8");
  counts[step] = (counts[step] || 0) + 1;
  stamped++;
}

console.log(`\n  stamped ${stamped} pages, skipped ${skipped}`);
for (const s of Object.keys(counts).sort()) {
  console.log(`    ${String(s).padStart(2, "0")} ${STEPS[s - 1].replace("&amp;", "&").padEnd(22)} ${counts[s]}`);
}
console.log("");
