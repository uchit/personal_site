#!/usr/bin/env node
/* build-mcp-data.mjs — one source of truth for the readiness check and the
 * ten controls, published three ways.
 *
 *   node scripts/build-mcp-data.mjs
 *
 * Reads:  js/pages/tools-agent-readiness.js (questions, levels, references)
 *         dataset/dataset.json             (the ten agent controls)
 *         js/readiness-score.js            (the one scoring function)
 * Writes: tools/agent-readiness.json       (public, machine-readable check)
 *         worker/site/src/generated/data.js           (MCP endpoint data)
 *         worker/site/src/generated/readiness-score.js (verbatim copy)
 *         the static question list inside src/pages/tools/agent-readiness.html,
 *         between <!-- STATIC-QUESTIONS --> markers, so the questions are in
 *         the HTML for crawlers and agents that do not run JavaScript.
 *
 * Run before build-site.mjs. CI rebuilds and fails if the output differs.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = p => readFileSync(join(ROOT, p), "utf8");
const write = (p, s) => { mkdirSync(dirname(join(ROOT, p)), { recursive: true }); writeFileSync(join(ROOT, p), s); };

/* Load the page's config by running its script with a stub Diag. */
let cfg;
new Function("window", "Diag", read("js/pages/tools-agent-readiness.js"))(
  { addEventListener: (_e, f) => f() }, { run: c => { cfg = c; } });
if (!cfg || cfg.questions.length !== 10) { console.error("could not load the readiness config"); process.exit(1); }

const ENT = { "&rsquo;": "’", "&lsquo;": "‘", "&ldquo;": "“", "&rdquo;": "”", "&amp;": "&",
  "&lt;": "<", "&gt;": ">", "&quot;": '"', "&hellip;": "…", "&nbsp;": " ", "&mdash;": ", ", "&ndash;": "-" };
const SITE = "https://hellouchit.com";
/* HTML fragment -> plain text (fragments are this repo's own config strings). */
function text(s) {
  let out = "", inTag = false;
  for (const ch of String(s ?? "")) {
    if (ch === "<") inTag = true;
    else if (ch === ">") inTag = false;
    else if (!inTag) out += ch;
  }
  return out.replace(/&[a-z]+;/gi, e => ENT[e.toLowerCase()] ?? "")
    .replace(/(\w)'(\w)/g, "$1’$2").replace(/\s+/g, " ").trim();
}
const absolute = u => (u && u.startsWith("/") ? SITE + u : u);
const refs = rs => (rs ?? []).map(r => ({ name: text(r.name), url: absolute(r.url) }));

const readiness = {
  name: "Agent readiness check",
  url: `${SITE}/tools/agent-readiness.html`,
  author: "Uchit Vyas",
  license: "https://creativecommons.org/licenses/by/4.0/",
  instructions: "Answer each question with the option number (1 to 5) that describes what is actually enforced today, not what is planned. The score is the sum of the ten answers, out of 50; the level comes from the score as a fraction of 50.",
  questions: cfg.questions.map((q, i) => ({
    number: i + 1, capability: text(q.cap), question: text(q.t),
    options: q.o.map((o, k) => ({ value: k + 1, text: text(o) })), references: refs(q.refs),
  })),
  levels: cfg.levels.map(l => ({
    name: l.name, minPct: l.minPct, maxPct: l.maxPct, summary: text(l.body), context: text(l.benchmark),
    recommendations: l.recs.map(r => ({ what: text(r.what), why: text(r.why), tools: text(r.tools),
      constraint: text(r.constraint), references: refs(r.refs) })),
  })),
  sectors: Object.fromEntries(Object.entries(cfg.sectors ?? {}).map(([k, s]) => [k, { label: text(s.label), lens: text(s.lens) }])),
};

const data = JSON.parse(read("dataset/dataset.json"));
const REG = data.regulations;
const controls = data.rows.filter(r => r.id.startsWith("agent-")).map(r => ({
  id: r.id, control: text(r.ctrl), surface: text(r.surface), why: text(r.notes), evidence: text(r.evidence),
  needsFirst: r.depends_on ?? [], mapsTo: r.reg.map(k => REG[k]?.label ?? k),
  verify: (r.verify ?? []).map(v => ({ platform: v.platform, command: v.run, expect: text(v.expect) })),
  tools: (r.tools ?? []).map(t => t[0]),
  url: `${SITE}/agents/#${r.id}`,
}));

write("tools/agent-readiness.json", JSON.stringify(readiness, null, 1) + "\n");
write("worker/site/src/generated/data.js",
  `// GENERATED by scripts/build-mcp-data.mjs. Do not edit.\n` +
  `export const READINESS = ${JSON.stringify(readiness)};\n` +
  `export const CONTROLS = ${JSON.stringify(controls)};\n`);
write("worker/site/src/generated/readiness-score.js",
  `// GENERATED copy of js/readiness-score.js by scripts/build-mcp-data.mjs. Do not edit.\n` + read("js/readiness-score.js"));

/* Static question list for the page: every question and option as plain
   HTML inside a disclosure, readable without JavaScript. */
const esc = s => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const list = `<!-- STATIC-QUESTIONS (generated by scripts/build-mcp-data.mjs) -->
    <details class="all-questions">
      <summary>See all ten questions</summary>
      <ol>
${readiness.questions.map(q => `        <li><p><b>${esc(q.capability)}.</b> ${esc(q.question)}</p>
          <ol class="opts-static">
${q.options.map(o => `            <li>${esc(o.text)}</li>`).join("\n")}
          </ol></li>`).join("\n")}
      </ol>
      <p class="small">Also available as <a href="/tools/agent-readiness.json">JSON</a>.</p>
    </details>
    <!-- /STATIC-QUESTIONS -->`;
const pagePath = "src/pages/tools/agent-readiness.html";
const page = read(pagePath);
const re = /<!-- STATIC-QUESTIONS[\s\S]*?<!-- \/STATIC-QUESTIONS -->/;
if (!re.test(page)) { console.error(`no STATIC-QUESTIONS markers in ${pagePath}`); process.exit(1); }
write(pagePath, page.replace(re, () => list));

console.log(`  readiness: ${readiness.questions.length} questions, ${readiness.levels.length} levels; controls: ${controls.length}`);
